import { chromium } from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1512,height:1050},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:5173');
 await page.getByRole('button',{name:'Enter workspace'}).click();
 await page.getByRole('heading',{name:/Your close/}).waitFor();
 await page.getByRole('navigation').getByRole('button',{name:'Financial overview',exact:true}).click();
 const before=await page.request.get('http://127.0.0.1:5173/api/state').then(r=>r.json());
 await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/phase2/reference')&&r.request().method()==='POST',{timeout:60000}),page.getByRole('button',{name:'Create reference close',exact:true}).click()]);
 await page.getByText('₹10,00,000',{exact:true}).first().waitFor({timeout:60000});
 const after=await page.request.get('http://127.0.0.1:5173/api/state').then(r=>r.json());
 if(JSON.stringify(before.uploads)!==JSON.stringify(after.uploads)||before.validation?.fingerprint!==after.validation?.fingerprint)throw new Error('Reference generation changed the active draft');
 await page.waitForTimeout(700);
 await page.screenshot({path:'../artifacts/phase2-overview.png',fullPage:true});
 await page.locator('.fact-table').getByRole('button',{name:/Cloud infrastructure/}).click();
 await page.getByRole('heading',{name:'Cloud infrastructure · Exact movement bridge',exact:true}).waitFor();
 await page.locator('.p2-driver-list').getByRole('button',{name:/^Usage/}).click();
 await page.getByRole('dialog',{name:'Variance evidence',exact:true}).waitFor();
 await page.getByText('+₹50,000',{exact:true}).last().waitFor();
 await page.locator('.p2-source-record').getByRole('button',{name:'Inspect',exact:true}).first().click();
 await page.locator('.evidence-original .source-values').waitFor();
 await page.screenshot({path:'../artifacts/phase2-evidence.png',fullPage:true});
 await page.getByRole('button',{name:'Close evidence',exact:true}).click();
 await page.getByRole('navigation').getByRole('button',{name:'Scenario Lab',exact:true}).click();
 await page.getByRole('slider',{name:'Vendor spending reduction',exact:true}).fill('2000');
 await page.getByRole('checkbox',{name:'Freeze POS-001',exact:true}).check();
 await page.getByText('₹33.00L',{exact:true}).first().waitFor();
 await page.waitForTimeout(600);
 await page.screenshot({path:'../artifacts/phase2-scenario.png',fullPage:true});
 await page.getByRole('textbox',{name:'Scenario name',exact:true}).fill('Golden browser plan');
 await page.getByRole('button',{name:'Save scenario',exact:true}).click();
 await page.getByText('Scenario saved with its exact assumptions.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Review cash assumptions',exact:true}).click();
 await page.getByRole('dialog',{name:'Review cash assumptions',exact:true}).waitFor();
 await page.screenshot({path:'../artifacts/phase2-assumptions.png',fullPage:true});
 await page.getByRole('button',{name:'Close dialog',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'../artifacts/phase2-mobile-scenario.png',fullPage:true});
 let overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 await page.getByRole('button',{name:'Financial overview',exact:true}).last().click();
 await page.screenshot({path:'../artifacts/phase2-mobile-overview.png',fullPage:true});
 overflow ||= await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 await page.getByRole('button',{name:'Variance Explorer',exact:true}).last().click();
 await page.screenshot({path:'../artifacts/phase2-mobile-variance.png',fullPage:true});
 overflow ||= await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 fs.writeFileSync('../artifacts/phase2-browser.json',JSON.stringify({errors,mobileHorizontalOverflow:overflow,checks:['reference close preserves draft','golden overview','cloud usage and source inspection','20% vendor reduction + uncommitted hire freeze','33 lakh closing cash','save scenario','assumptions editor','desktop and mobile navigation']},null,2));
 if(errors.length||overflow)throw new Error(JSON.stringify({errors,overflow}));
 console.log('Phase 2 browser acceptance flow passed.');
}finally{await browser.close()}
