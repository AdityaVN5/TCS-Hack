import { chromium } from '@playwright/test';
import fs from 'node:fs';

const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1512,height:1050},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const checks=[];
const overflow=[];
async function capture(name){
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.waitForTimeout(180);
 await page.screenshot({path:`../artifacts/refined-${name}.png`,fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))overflow.push(name);
}
try{
 await page.goto('http://127.0.0.1:5173/#workspace');
 await page.getByRole('button',{name:'Enter workspace'}).click();
 await page.getByRole('heading',{name:/Your close/}).waitFor();
 await capture('workspace');
 const font=await page.locator('h1').evaluate(el=>getComputedStyle(el).fontFamily);
 if(!font.includes('-apple-system'))throw new Error('System typography was not applied');
 checks.push('Workspace has one next action and native system typography');
 await page.getByRole('navigation',{name:'Getting started'}).getByRole('button',{name:'How it works',exact:true}).click();
 await page.getByRole('heading',{name:/From spreadsheets/}).waitFor();
 if(await page.locator('.guide-step').count()!==9)throw new Error('The complete nine-step guide is missing');
 await page.locator('.guide-step').first().locator('summary').click();
 await page.locator('.guide-step').first().getByRole('button',{name:'Open workspace settings'}).click();
 await page.getByRole('dialog',{name:'Workspace essentials'}).waitFor();
 await page.getByRole('button',{name:'Close dialog',exact:true}).click();
 await capture('guide');
 await page.reload();
 await page.getByRole('heading',{name:/From spreadsheets/}).waitFor();
 if(!page.url().endsWith('#guide'))throw new Error('Guide direct link was not retained');
 checks.push('Dedicated guide, nine steps, settings action, and reloadable deep link');
 await page.getByRole('button',{name:'Start with your files',exact:true}).click();
 await page.getByRole('heading',{name:'Source files.',exact:true}).waitFor();
 if(await page.locator('.demo-card').evaluate(el=>el.open))throw new Error('Sample-data detail should begin collapsed');
 await capture('uploads');
 await page.getByRole('navigation',{name:'Data workspace'}).getByRole('button',{name:'Review mappings',exact:true}).click();
 await page.getByRole('heading',{name:'Map your data.',exact:true}).waitFor();
 if(await page.locator('.optional-mappings').count()){
  if(await page.locator('.optional-mappings').evaluate(el=>el.open))throw new Error('Optional mappings should begin collapsed');
  await page.locator('.optional-mappings > summary').click();
  await page.locator('.preview-panel > summary').click();
 }
 await capture('mappings');
 checks.push('File and mapping detail remains available through disclosures');
 await page.getByRole('navigation',{name:'Financial analysis'}).getByRole('button',{name:'Financial overview',exact:true}).click();
 await page.getByRole('heading',{name:'Financial overview.',exact:true}).waitFor();
 await page.locator('.p2-kpis').waitFor();
 if(await page.getByLabel('Department filter',{exact:true}).isVisible())throw new Error('Advanced filters should begin collapsed');
 await page.getByRole('button',{name:'Filters',exact:true}).click();
 await page.getByLabel('Department filter',{exact:true}).selectOption('Engineering');
 await page.locator('.fact-table tbody tr').first().waitFor();
 await page.waitForTimeout(350);
 await page.getByLabel('Department filter',{exact:true}).selectOption('');
 await page.waitForTimeout(350);
 await page.getByRole('button',{name:'Filters',exact:true}).click();
 await capture('overview');
 await page.locator('.fact-table').getByRole('button',{name:/Cloud infrastructure/}).click();
 await page.getByRole('heading',{name:'Variance Explorer.',exact:true}).waitFor();
 await page.locator('.p2-driver-list button').first().click();
 await page.getByRole('dialog',{name:'Variance evidence'}).waitFor();
 await page.getByRole('button',{name:'Close evidence',exact:true}).click();
 await capture('variance');
 checks.push('On-demand filters, account drilldown, and evidence drawer');
 await page.getByRole('navigation',{name:'Financial analysis'}).getByRole('button',{name:'Scenario Lab',exact:true}).click();
 await page.getByRole('slider',{name:'Vendor spending reduction'}).waitFor();
 const schedule=page.locator('.p2-schedule');
 if(await schedule.evaluate(el=>el.open))throw new Error('Cash schedule should begin collapsed');
 await schedule.locator('summary').click();
 if(await schedule.locator('tbody tr').count()!==12)throw new Error('Cash schedule lost its twelve months');
 await schedule.locator('summary').click();
 await capture('scenarios');
 checks.push('Cash model, controls, and full schedule retained');
 await page.setViewportSize({width:390,height:844});
 await capture('mobile-scenarios');
 await page.getByRole('navigation',{name:'Data workspace'}).getByRole('button',{name:'How it works',exact:true}).click();
 await page.getByRole('heading',{name:/From spreadsheets/}).waitFor();
 await capture('mobile-guide');
 await page.getByRole('button',{name:'Start with your files',exact:true}).click();
 await capture('mobile-uploads');
 await page.getByRole('navigation',{name:'Data workspace'}).getByRole('button',{name:'Analyze',exact:true}).click();
 await page.locator('.p2-kpis').waitFor();
 await capture('mobile-overview');
 await page.setViewportSize({width:820,height:1180});
 await capture('tablet-overview');
 checks.push('Mobile and tablet navigation without horizontal page overflow');
 fs.writeFileSync('../artifacts/refinement-browser.json',JSON.stringify({errors,overflow,checks},null,2));
 if(errors.length||overflow.length)throw new Error(JSON.stringify({errors,overflow}));
 console.log('Refined UI and guide browser checks passed.');
}finally{await browser.close()}
